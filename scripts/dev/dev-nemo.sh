#!/usr/bin/env bash
# Safely switch Nemo right-click integration (`Open in Radivine`) between the workspace development
# build and the installed system package without modifying `/usr/bin` or `/usr/share/nemo/actions`.

set -euo pipefail

# shellcheck source=scripts/dev/common.sh
source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/common.sh"

usage() {
    cat <<'EOF'
Usage:
  ./scripts/dev/dev-nemo.sh enable [--release|--debug]
  ./scripts/dev/dev-nemo.sh restore
  ./scripts/dev/dev-nemo.sh status

Commands:
  enable    Install user-scoped Nemo action (~/.local/share/nemo/actions/radivine-dev.nemo_action)
            pointing to the workspace development daemon and temporarily hide the system
            /usr/share/nemo/actions/radivine.nemo_action entry in Nemo.
  restore   Remove the development Nemo action and restore the original Nemo disabled-actions list.
  status    Show current Nemo integration state and active paths.
EOF
}

mask_system_nemo_action() {
    if ! command -v gsettings >/dev/null 2>&1; then
        return 0
    fi
    local current
    current="$(gsettings get org.nemo.plugins disabled-actions 2>/dev/null || true)"
    if [[ -z "${current}" ]]; then
        return 0
    fi

    # Save the original GVariant string once so `restore` can restore it verbatim
    if [[ ! -f "${DEV_NEMO_BACKUP_FILE}" ]]; then
        printf '%s\n' "${current}" > "${DEV_NEMO_BACKUP_FILE}"
    fi

    # Add 'radivine.nemo_action' if not already present
    if [[ "${current}" != *"'radivine.nemo_action'"* ]]; then
        local updated
        if [[ "${current}" == "@as []" || "${current}" == "[]" ]]; then
            updated="['radivine.nemo_action']"
        else
            updated="${current%]}, 'radivine.nemo_action']"
        fi
        gsettings set org.nemo.plugins disabled-actions "${updated}" 2>/dev/null || true
    fi
}

unmask_system_nemo_action() {
    if [[ -f "${DEV_NEMO_BACKUP_FILE}" ]]; then
        if command -v gsettings >/dev/null 2>&1; then
            local orig
            orig="$(cat "${DEV_NEMO_BACKUP_FILE}")"
            if [[ -n "${orig}" ]]; then
                gsettings set org.nemo.plugins disabled-actions "${orig}" 2>/dev/null || true
            fi
        fi
        rm -f "${DEV_NEMO_BACKUP_FILE}"
    fi
}

cmd_enable() {
    local profile
    profile="$(get_active_profile)"
    while [[ $# -gt 0 ]]; do
        case "$1" in
            --release)
                profile="release"
                shift
                ;;
            --debug)
                profile="debug"
                shift
                ;;
            *)
                dev_err "Unknown option for enable: $1"
                usage
                exit 2
                ;;
        esac
    done

    write_dev_env_file "${profile}"
    mkdir -p "${USER_NEMO_ACTIONS_DIR}"

    cat > "${DEV_NEMO_INVOKE_SCRIPT}" <<EOF
#!/usr/bin/env bash
# Auto-generated by scripts/dev/dev-nemo.sh — invokes the workspace development Radivine wheel.
set -euo pipefail

DEV_ENV="${DEV_ENV_FILE}"
if [[ ! -f "\${DEV_ENV}" ]]; then
    echo "Radivine dev environment file not found at \${DEV_ENV}" >&2
    exit 1
fi
# shellcheck disable=SC1090
source "\${DEV_ENV}"

exec "\${RADIVINE_DAEMON_BIN}" --socket "\${RADIVINE_SOCKET}" invoke "\$@"
EOF
    chmod 0755 "${DEV_NEMO_INVOKE_SCRIPT}"

    cat > "${DEV_NEMO_ACTION_FILE}" <<'EOF'
[Nemo Action]
Active=true
Name=Open in Radivine (Dev)
Comment=Summon the development Radivine radial action wheel for the selected items
Exec=<radivine-dev-invoke.sh %F>
Icon-Name=radivine
Selection=notnone
Extensions=any;
Quote=double
EOF
    chmod 0644 "${DEV_NEMO_ACTION_FILE}"

    if [[ -f "${SYSTEM_NEMO_ACTION}" ]]; then
        mask_system_nemo_action
    fi

    dev_ok "Enabled development Nemo integration (${profile} profile)"
    printf '  Action file:   %s\n' "${DEV_NEMO_ACTION_FILE}"
    printf '  Invoke script: %s\n' "${DEV_NEMO_INVOKE_SCRIPT}"
    printf '  Dev binary:    %s/radivine\n' "$(resolve_target_dir "${profile}")"
    printf '  Dev socket:    %s\n' "${DEV_DAEMON_SOCKET}"
}

cmd_restore() {
    local removed=0
    if [[ -f "${DEV_NEMO_ACTION_FILE}" ]]; then
        rm -f "${DEV_NEMO_ACTION_FILE}"
        removed=1
    fi
    if [[ -f "${DEV_NEMO_INVOKE_SCRIPT}" ]]; then
        rm -f "${DEV_NEMO_INVOKE_SCRIPT}"
        removed=1
    fi
    unmask_system_nemo_action

    if [[ "${removed}" -eq 1 ]]; then
        dev_ok "Restored original Nemo integration (removed development action override)"
    else
        dev_info "Development Nemo override was not active; original state verified"
    fi
}

cmd_status() {
    if is_nemo_dev_enabled; then
        printf 'Nemo Integration:  DEVELOPMENT OVERRIDE ACTIVE\n'
        printf '  User action:     %s\n' "${DEV_NEMO_ACTION_FILE}"
        printf '  Wrapper script:  %s\n' "${DEV_NEMO_INVOKE_SCRIPT}"
    else
        printf 'Nemo Integration:  SYSTEM DEFAULT\n'
    fi
    if [[ -f "${SYSTEM_NEMO_ACTION}" ]]; then
        local disabled_list=""
        if command -v gsettings >/dev/null 2>&1; then
            disabled_list="$(gsettings get org.nemo.plugins disabled-actions 2>/dev/null || true)"
        fi
        if [[ "${disabled_list}" == *"'radivine.nemo_action'"* ]]; then
            printf '  System action:   %s (temporarily masked while dev override is active)\n' "${SYSTEM_NEMO_ACTION}"
        else
            printf '  System action:   %s (active)\n' "${SYSTEM_NEMO_ACTION}"
        fi
    else
        printf '  System action:   (not installed)\n'
    fi
}

subcmd="${1:-status}"
if [[ $# -gt 0 ]]; then
    shift
fi

case "${subcmd}" in
    enable)
        cmd_enable "$@"
        ;;
    restore|disable)
        cmd_restore
        ;;
    status)
        cmd_status
        ;;
    -h|--help|help)
        usage
        ;;
    *)
        dev_err "Unknown subcommand: ${subcmd}"
        usage
        exit 2
        ;;
esac
