#!/usr/bin/env bash
# Shared helpers and isolated runtime paths for Radivine development scripts.
# Sourced by `dev-start.sh`, `dev-stop.sh`, `dev-restart.sh`, `dev-status.sh`, and `dev-nemo.sh`.

set -euo pipefail

DEV_SCRIPTS_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${DEV_SCRIPTS_DIR}/../.." && pwd)"

# Isolated development root inside the workspace (gitignored)
DEV_ROOT="${RADIVINE_DEV_ROOT:-${REPO_ROOT}/.radivine-dev}"
DEV_CONFIG_HOME="${DEV_ROOT}/config"
DEV_STATE_HOME="${DEV_ROOT}/state"
DEV_CACHE_HOME="${DEV_ROOT}/cache"

# Isolated runtime directory for Unix domain sockets & PID files
UID_NUM="$(id -u)"
BASE_RUNTIME_DIR="${XDG_RUNTIME_DIR:-/tmp/radivine-runtime-${UID_NUM}}"
DEV_RUNTIME_DIR="${RADIVINE_DEV_RUNTIME_DIR:-${BASE_RUNTIME_DIR}/radivine-dev}"

DEV_DAEMON_SOCKET="${DEV_RUNTIME_DIR}/radivine.sock"
DEV_WORKER_SOCKET="${DEV_RUNTIME_DIR}/worker.sock"
DEV_WORKER_LOCK="${DEV_RUNTIME_DIR}/worker.lock"
DEV_CONTROL_SOCKET="${DEV_RUNTIME_DIR}/control.sock"

DEV_DAEMON_PID_FILE="${DEV_RUNTIME_DIR}/daemon.pid"
DEV_WORKER_PID_FILE="${DEV_RUNTIME_DIR}/worker.pid"
DEV_CONTROL_PID_FILE="${DEV_RUNTIME_DIR}/control.pid"

DEV_DAEMON_LOG="${DEV_STATE_HOME}/radivine/daemon.log"
DEV_WORKER_LOG="${DEV_STATE_HOME}/radivine/worker.log"
DEV_WORKER_DB="${DEV_STATE_HOME}/radivine/jobs.sqlite3"

DEV_PROFILE_FILE="${DEV_ROOT}/active-profile"
DEV_ENV_FILE="${DEV_ROOT}/env.sh"
DEV_INSTALLED_STATE_FILE="${DEV_ROOT}/installed-service.state"
DEV_NEMO_BACKUP_FILE="${DEV_ROOT}/nemo-disabled-actions.orig"

# System / installed paths (read-only inspection)
SYSTEM_RUNTIME_SOCKET="${BASE_RUNTIME_DIR}/radivine/radivine.sock"
SYSTEM_NEMO_ACTION="/usr/share/nemo/actions/radivine.nemo_action"

# User Nemo actions directory (`~/.local/share/nemo/actions`)
USER_DATA_HOME="${XDG_DATA_HOME:-${HOME}/.local/share}"
USER_NEMO_ACTIONS_DIR="${USER_DATA_HOME}/nemo/actions"
DEV_NEMO_ACTION_FILE="${USER_NEMO_ACTIONS_DIR}/radivine-dev.nemo_action"
DEV_NEMO_INVOKE_SCRIPT="${USER_NEMO_ACTIONS_DIR}/radivine-dev-invoke.sh"

# Real user config directory (used only as a read-only seed on first dev run)
REAL_USER_CONFIG_DIR="${HOME}/.config/radivine"

dev_info() {
    printf '\033[1;34m==>\033[0m %s\n' "$*"
}

dev_ok() {
    printf '\033[1;32m[OK]\033[0m %s\n' "$*"
}

dev_warn() {
    printf '\033[1;33m[WARN]\033[0m %s\n' "$*" >&2
}

dev_err() {
    printf '\033[1;31m[ERROR]\033[0m %s\n' "$*" >&2
}

get_active_profile() {
    if [[ -f "${DEV_PROFILE_FILE}" ]]; then
        local prof
        prof="$(tr -d '[:space:]' < "${DEV_PROFILE_FILE}")"
        if [[ "${prof}" == "debug" || "${prof}" == "release" ]]; then
            printf '%s\n' "${prof}"
            return 0
        fi
    fi
    printf 'release\n'
}

resolve_target_dir() {
    local profile="${1:-release}"
    if [[ "${profile}" == "debug" ]]; then
        printf '%s/target/debug\n' "${REPO_ROOT}"
    else
        printf '%s/target/release\n' "${REPO_ROOT}"
    fi
}

ensure_dev_dirs() {
    mkdir -p \
        "${DEV_CONFIG_HOME}/radivine" \
        "${DEV_STATE_HOME}/radivine" \
        "${DEV_CACHE_HOME}" \
        "${DEV_RUNTIME_DIR}"
    chmod 0700 "${DEV_RUNTIME_DIR}" "${DEV_STATE_HOME}/radivine" 2>/dev/null || true

    # Preserve GTK dark/light theme auto-detection inside isolated XDG_CONFIG_HOME
    for gtk_dir in gtk-3.0 gtk-4.0; do
        if [[ -d "${HOME}/.config/${gtk_dir}" && ! -e "${DEV_CONFIG_HOME}/${gtk_dir}" ]]; then
            ln -s "${HOME}/.config/${gtk_dir}" "${DEV_CONFIG_HOME}/${gtk_dir}" 2>/dev/null || true
        fi
    done

    # Seed isolated dev config once from ~/.config/radivine if present (never modifies real user files)
    if [[ -d "${REAL_USER_CONFIG_DIR}" ]]; then
        for cfg_name in config.toml actions.toml convert.toml; do
            if [[ -f "${REAL_USER_CONFIG_DIR}/${cfg_name}" && ! -f "${DEV_CONFIG_HOME}/radivine/${cfg_name}" ]]; then
                cp -p "${REAL_USER_CONFIG_DIR}/${cfg_name}" "${DEV_CONFIG_HOME}/radivine/${cfg_name}"
                dev_info "Seeded isolated dev ${cfg_name} from ${REAL_USER_CONFIG_DIR}/${cfg_name}"
            fi
        done
    fi
}

write_dev_env_file() {
    local profile="${1:-release}"
    local target_dir
    target_dir="$(resolve_target_dir "${profile}")"

    ensure_dev_dirs
    printf '%s\n' "${profile}" > "${DEV_PROFILE_FILE}"

    cat > "${DEV_ENV_FILE}" <<EOF
# Auto-generated by scripts/dev/ — source this file to run Radivine CLI tools against the dev instance.
export RADIVINE_DEV_MODE="1"
export RADIVINE_DEV_PROFILE="${profile}"
export RADIVINE_DEV_ROOT="${DEV_ROOT}"
export RADIVINE_DAEMON_BIN="${target_dir}/radivine"
export RADIVINE_WORKER_BIN="${target_dir}/radivine-worker"
export RADIVINE_CONTROL_BIN="${target_dir}/radivine-control"
export RADIVINE_VIEWER_BIN="${target_dir}/radivine-viewer"
export RADIVINE_SOCKET="${DEV_DAEMON_SOCKET}"
export RADIVINE_WORKER_SOCKET="${DEV_WORKER_SOCKET}"
export RADIVINE_WORKER_LOCK="${DEV_WORKER_LOCK}"
export RADIVINE_WORKER_DB="${DEV_WORKER_DB}"
export RADIVINE_WORKER_LOG="${DEV_WORKER_LOG}"
export RADIVINE_CONTROL_SOCKET="${DEV_CONTROL_SOCKET}"
export RADIVINE_WORKER_LAUNCH="spawn"
export RADIVINE_CONTROL_FORCE_FALLBACK="1"
export RADIVINE_DISABLE_SYSTEMD_USER_SPAWN="1"
export XDG_CONFIG_HOME="${DEV_CONFIG_HOME}"
export XDG_STATE_HOME="${DEV_STATE_HOME}"
export XDG_CACHE_HOME="${DEV_CACHE_HOME}"
export PATH="${target_dir}:\${PATH}"
EOF
    chmod 0600 "${DEV_ENV_FILE}"
}

load_dev_env() {
    local profile="${1:-$(get_active_profile)}"
    if [[ ! -f "${DEV_ENV_FILE}" ]]; then
        write_dev_env_file "${profile}"
    fi
    # shellcheck disable=SC1090
    source "${DEV_ENV_FILE}"
}

# Verifies that <pid> is alive AND its executable resides under $REPO_ROOT/target/
is_pid_owned_by_workspace() {
    local pid="${1:-}"
    if [[ -z "${pid}" || ! "${pid}" =~ ^[0-9]+$ ]]; then
        return 1
    fi
    if ! kill -0 "${pid}" 2>/dev/null; then
        return 1
    fi
    local exe_path
    exe_path="$(readlink -f "/proc/${pid}/exe" 2>/dev/null || true)"
    exe_path="${exe_path% (deleted)}"
    if [[ -z "${exe_path}" ]]; then
        return 1
    fi
    case "${exe_path}" in
        "${REPO_ROOT}/target/"*)
            return 0
            ;;
        *)
            return 1
            ;;
    esac
}

get_pid_exe() {
    local pid="${1:-}"
    if [[ -z "${pid}" || ! "${pid}" =~ ^[0-9]+$ ]]; then
        return 1
    fi
    local exe_path
    exe_path="$(readlink -f "/proc/${pid}/exe" 2>/dev/null || true)"
    printf '%s\n' "${exe_path% (deleted)}"
}

# Returns the running dev daemon PID if and only if owned by this workspace
get_dev_daemon_pid() {
    local pid=""
    if [[ -f "${DEV_DAEMON_PID_FILE}" ]]; then
        pid="$(tr -d '[:space:]' < "${DEV_DAEMON_PID_FILE}" 2>/dev/null || true)"
        if is_pid_owned_by_workspace "${pid}"; then
            printf '%s\n' "${pid}"
            return 0
        fi
    fi

    # Fallback: query the dev daemon socket directly
    local profile
    profile="$(get_active_profile)"
    local target_dir
    target_dir="$(resolve_target_dir "${profile}")"
    local bin="${target_dir}/radivine"
    if [[ -x "${bin}" && -S "${DEV_DAEMON_SOCKET}" ]]; then
        local status_json
        status_json="$("${bin}" --socket "${DEV_DAEMON_SOCKET}" status --json 2>/dev/null || true)"
        if [[ -n "${status_json}" ]]; then
            pid="$(printf '%s\n' "${status_json}" | sed -n 's/.*"pid"[[:space:]]*:[[:space:]]*\([0-9][0-9]*\).*/\1/p' | head -n 1)"
            if is_pid_owned_by_workspace "${pid}"; then
                printf '%s\n' "${pid}" > "${DEV_DAEMON_PID_FILE}"
                printf '%s\n' "${pid}"
                return 0
            fi
        fi
    fi
    return 1
}

