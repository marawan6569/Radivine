is_installed_systemd_service_active() {
    if command -v systemctl >/dev/null 2>&1; then
        local st
        st="$(systemctl --user is-active radivine.service 2>/dev/null || true)"
        if [[ "${st}" == "active" || "${st}" == "activating" ]]; then
            return 0
        fi
    fi
    return 1
}

get_system_socket_daemon_pid() {
    if [[ ! -S "${SYSTEM_RUNTIME_SOCKET}" ]]; then
        return 1
    fi
    local bin="/usr/bin/radivine"
    if [[ ! -x "${bin}" ]]; then
        local profile
        profile="$(get_active_profile)"
        bin="$(resolve_target_dir "${profile}")/radivine"
    fi
    if [[ -x "${bin}" ]]; then
        local status_json
        status_json="$("${bin}" --socket "${SYSTEM_RUNTIME_SOCKET}" status --json 2>/dev/null || true)"
        if [[ -n "${status_json}" ]]; then
            local pid
            pid="$(printf '%s\n' "${status_json}" | sed -n 's/.*"pid"[[:space:]]*:[[:space:]]*\([0-9][0-9]*\).*/\1/p' | head -n 1)"
            if [[ -n "${pid}" ]] && kill -0 "${pid}" 2>/dev/null; then
                printf '%s\n' "${pid}"
                return 0
            fi
        fi
    fi
    return 1
}

is_nemo_dev_enabled() {
    [[ -f "${DEV_NEMO_ACTION_FILE}" && -x "${DEV_NEMO_INVOKE_SCRIPT}" ]]
}
